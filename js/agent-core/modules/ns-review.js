// ===== 国家安全学 120 维度审稿扫描 =====
import { callModel } from '../model-bridge.js';

const GROUPS = [
  ['概念界定', '核心概念内涵外延是否闭合；是否存在概念偷换（如把“安全化”等同于“安全议题增加”）；相邻概念是否区分（排他性治理 vs 霸权治理、棘轮效应 vs 路径依赖）'],
  ['理论适用', '理论是否真正参与解释而非装饰；是否存在削足适履；理论对话对象是否明确；竞争性理论是否被排除'],
  ['因果机制', '机制是否可观察；过程追踪证据是否落在节点上；是否存在相关冒充因果；反事实是否讨论'],
  ['案例效度', '案例选择是否系统性偏差；单案例外推边界是否交代；样本内变异是否利用；反例是否纳入'],
  ['证据强度', '关键判断是否有可追溯来源；数据口径是否一致；引证是否支撑原句观点；是否存在挂空文献'],
  ['论证逻辑', '前提与结论是否断裂；是否存在循环论证；定义是否被结论反噬；章节间论证是否承接'],
  ['政策表述', '是否触碰不宜公开表述；政策建议是否越位；是否混淆实然与应然；涉密与敏感信息是否被处理'],
  ['术语一致', '同一概念全文用词是否统一；中英译名是否规范；缩写首次出现是否给全称'],
  ['写作规范', '是否存在 AI 腔、排比堆砌、口号化；段落是否有主题句；图表与正文是否互指'],
  ['文献对话', '是否只罗列不评价；是否漏掉关键中文文献；近三年进展是否覆盖；是否与自身研究真正衔接']
];

const SYS = [
  '你是 CSSCI 顶刊资深审稿人，专项审查国家安全学、国际关系、区域安全治理方向稿件。',
  '按十组维度（每组下含 12 个检查点，共 120 项）逐段扫描文稿。',
  '',
  '审查维度：',
  GROUPS.map((g, i) => (i + 1) + '. ' + g[0] + '：' + g[1]).join('\n'),
  '',
  '输出要求：',
  '## 整体判定',
  '给出评级：可直接送审 / 小修 / 大修 / 不宜投稿，并给一句核心理由',
  '## 逐条问题清单',
  '格式：位置（引用原文片段 15 字内）｜维度｜问题描述｜风险等级（低/中/高）｜建议替换措辞',
  '只列真实存在的问题，没有问题的维度写“未见明显问题”，不要凑数',
  '## 必须补充的支撑',
  '列出需要补引文、补数据、补反例的具体位置',
  '## 返修核对清单',
  '按优先级排序的待办，可直接当修改 checklist'
].join('\n');

export async function runNSReview(params) {
  const text = (params.text || '').trim();
  if (!text) throw new Error('没有可审查的文稿');

  const user = [
    '目标期刊：' + (params.journal || '太平洋学报'),
    '审查深度：' + (params.depth ? '深度（逐段，允许长输出）' : '常规'),
    '',
    '文稿：',
    text.slice(0, 30000)
  ].join('\n');

  const out = await callModel(SYS, user, {
    temperature: 0.15,
    maxTokens: params.depth ? 6000 : 4096
  });

  // 粗略抽取风险条目计数，便于 UI 概览
  const high = (out.match(/风险等级[：:]\s*高|｜高/g) || []).length;
  const mid = (out.match(/风险等级[：:]\s*中|｜中/g) || []).length;

  return { text: out, high, mid };
}
